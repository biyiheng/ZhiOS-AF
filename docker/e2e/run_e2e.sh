#!/usr/bin/env bash
# =============================================================================
# run_e2e.sh - 容器内端到端综合验证入口（Docker e2e 镜像 CMD）
#
# 依次验证三个层面，确保 Agent 控制软件在 Docker 环境下端到端通畅：
#   1) Agent 控制软件：前端 + 后端 + 数据库 + 全功能模块（e2e_test.py）
#   2) 防火墙逻辑    ：C 层 firewall.c（默认拒绝/白名单/源白名单/长度/限速）
#   3) 驱动接口      ：UART 环形缓冲驱动（FIFO/满丢弃/空读/回绕）
#
# 退出码 0 = 全部通过；非 0 = 存在失败项（供 docker compose/CI 判定）。
# =============================================================================
set -uo pipefail
fail=0

echo "########## [1/3] Agent 控制软件端到端测试（前后端+数据库+功能模块）##########"
python /app/e2e_test.py || fail=1

echo
echo "########## [2/3] 防火墙逻辑验证（C 层 firewall.c）##########"
/app/fw_test || fail=1

echo
echo "########## [3/3] 驱动接口验证（UART 环形缓冲）##########"
/app/uart_drv_test || fail=1

echo
echo "======================================================"
if [ "$fail" = "0" ]; then
  echo "==> 容器端到端综合验证 ALL PASS"
else
  echo "==> 容器端到端综合验证：存在失败项"
fi
echo "======================================================"
exit "$fail"
